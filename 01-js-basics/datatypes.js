// Loose Typing and Primitive Data Types in Node.js

// Variable storing number data type
let a = 35;
console.log("Type of a (35):", typeof a);

// Variable storing string data type
a = "NodeJS Example";
console.log("Type of a ('NodeJS Example'):", typeof a);

// Variable storing Boolean data type
a = true;
console.log("Type of a (true):", typeof a);

// Variable storing undefined data type
a = undefined;
console.log("Type of a (undefined):", typeof a);
